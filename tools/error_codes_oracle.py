# name -> code, code -> name
CODE = {name: i + 1 for i, (name, _r, _s, _d) in enumerate(CANON)}
NAME = {i + 1: name for i, (name, _r, _s, _d) in enumerate(CANON)}
STANDARDS_MAX = 0x7FFF  # >= 0x8000 is private-use (no registration)


def naalp_error_body(code, name, detail=None, subject=None):
    """Canonical CBOR of the naalp-error body map {1:code, 2:name, ?3:detail, ?4:subject}.
    Integer keys 1..4 are already in canonical ascending order."""
    pairs = [(1, code), (2, name)]
    if detail is not None:
        pairs.append((3, detail))
    if subject is not None:
        pairs.append((4, subject))
    return enc(("map", pairs))


def build():
    errors = [{"code": i + 1, "name": name, "retryable": retry, "subsystem": sub, "desc": desc}
              for i, (name, retry, sub, desc) in enumerate(CANON)]
    # ordered name array: NameForCode(code) == names[code-1]; code == index+1. This is the minimal
    # representation each port embeds (an ordered list of names), and the source the port table is
    # graded against by the error.name_for_code op.
    names = [name for (name, _r, _s, _d) in CANON]

    # error.encode KATs: a representative spread of codes (short/long names, the extremes) plus the
    # two full-grammar cases carrying detail (field 3) and a real content-id-shaped subject (field 4;
    # multihash 0x20/sha2-384 + 48-octet digest). One or two per subsystem is enough to grade the
    # body encoding across all ten adapters -- the per-code TABLE is graded by error.name_for_code.
    subj = bytes([0x20, 0x30]) + bytes(range(48))
    enc_specs = [
        ("NonCanonical", None, None), ("Malformed", None, None), ("WrongAudience", None, None),
        ("BadSignature", None, None), ("NotDelivered", None, None), ("ScopeOverlapConflict", None, None),
        ("ReconcileMismatch", None, None), ("RebindUnauthorized", None, None),
        ("BadSignature", "verifier reason: see log", subj.hex()),
        ("WrongAudience", "audience was other-endpoint", subj.hex()),
    ]
    encode_cases = []
    for i, (nm, detail, subj_hex) in enumerate(enc_specs, 1):
        s = None if subj_hex is None else bytes.fromhex(subj_hex)
        encode_cases.append({
            "tcId": i, "code": CODE[nm], "name": nm, "detail": detail, "subject_hex": subj_hex,
            "want_hex": naalp_error_body(CODE[nm], nm, detail, s).hex(),
        })

    # error.decode KATs: canonical round-trips (accept), the dual-carriage MUST-REJECT (registered
    # code with the wrong registered name -> Malformed), and the unknown-code opaque case (accept).
    decode_cases = []
    di = 0
    for nm in ("NonCanonical", "BadSignature", "NotDelivered", "RebindUnauthorized"):
        di += 1
        decode_cases.append({
            "tcId": di, "in_hex": naalp_error_body(CODE[nm], nm).hex(),
            "want": {"code": CODE[nm], "name": nm}, "reject": None,
            "note": "canonical %s round-trips" % nm,
        })
    di += 1
    decode_cases.append({
        "tcId": di, "in_hex": naalp_error_body(CODE["BadSignature"], "NotDelivered").hex(),
        "want": None, "reject": "Malformed",
        "note": "code=22 (BadSignature) but name=NotDelivered: registered code + wrong name -> Malformed",
    })
    di += 1
    unknown = 60000  # standards-range but unassigned in this document
    decode_cases.append({
        "tcId": di, "in_hex": naalp_error_body(unknown, "SomeFutureError").hex(),
        "want": {"code": unknown, "name": "SomeFutureError"}, "reject": None,
        "note": "unknown code is opaque and non-fatal (open registry, RFC Required)",
    })

    return {
        "channel": 0, "kind": 3,  # Control/Error surface (§3.2)
        "standards_max": STANDARDS_MAX,
        "unknown_code_example": unknown,
        "errors": errors,
        "names": names,
        "encode_cases": encode_cases,
        "decode_cases": decode_cases,
    }


def write_cases(doc):
    outdir = os.path.join(ROOT, "vectors", "error_codes")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "cases.json"), "w", newline="\n", encoding="utf-8") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")


def write_csv(doc):
    # vectors/registry/error-codes.csv is the human-readable registry authority, generated from the
    # same CANON as the byte cases so the two cannot drift; the drift gate checks CSV <-> CDDL enum.
    outdir = os.path.join(ROOT, "vectors", "registry")
    lines = ["code,name,retryable,subsystem,description"]
    for e in doc["errors"]:
        # description has no commas by construction; quote defensively anyway.
        desc = e["desc"].replace('"', "'")
        lines.append('%d,%s,%s,%s,"%s"' % (e["code"], e["name"],
                                           "yes" if e["retryable"] else "no", e["subsystem"], desc))
    # encoding="utf-8" is REQUIRED for cross-platform byte-determinism: without it, text
    # mode uses the platform default (cp1252 on Windows, utf-8 on Linux CI), so the "§"
    # in subsystem-section descriptions encodes as 0xA7 vs 0xC2A7 and the file's pinned
    # SHA-256 drifts between a Windows-authored commit and the Linux CI regeneration.
    with open(os.path.join(outdir, "error-codes.csv"), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def cddl_enum(doc):
    """Emit the `naalp-error-code` CDDL enum block (for insertion into spec/naalp-draft-01.cddl).
    The body grammar uses `code: uint` (NOT this enum) so a future/private code still validates;
    this enum is the named taxonomy the drift gate checks the CSV against."""
    lines = ["naalp-error-code = &("]
    for e in doc["errors"]:
        lines.append("  %s: %d," % (e["name"], e["code"]))
    lines.append(")")
    return "\n".join(lines)


