"""
N-AALP Error Code registry + naalp-error object oracle (design.md §3.5, R3.3/R3.4, T3.3).

This is the independent byte + taxonomy authority for the "N-AALP Error Codes" registry and the
`naalp-error` object body carried on the Control/Error surface (channel 0x0000, kind 3). It shares
no code with impl/go or impl/rust; Go, Rust, and the eight other ports are graded by reproducing
the bytes and the name<->code mapping this file emits (non-circular, F3 / CLAUDE.md).

WHAT IS REGISTERED (scope discriminator, advisor-ruled 2026-08-23): every protocol error the
specification defines as a fail-closed rejection reason returnable by a verify/decode path on
peer-supplied input -- the spine AND all twenty channel surfaces. EXCLUDED are purely local errors
never carried to a peer: the encoder-side `Unencodable`, and the key-generation input errors
`SeedSize` / `KeyMalformed`. `Malformed` is the generic fallback. `FlowControlError` is a
transport-binding property, not an N-AALP object rejection, and is not registered.

CODE ASSIGNMENT (fields of record): codes are assigned sequentially from 1 in the documented
subsystem order below (spine first, then the channel surfaces in build order); 0 is reserved and
MUST NOT appear on the wire. The standards range is 1..0x7FFF (RFC Required / FCFS, ISE-permissible
per the runbook); >=0x8000 is private-use, no registration. The order -- not any per-error choice
-- is the named source for every code, so the scheme is reproducible.

RETRYABLE (fields of record): true iff an unmodified retry of the same object can later succeed
because of a transient/environmental change with no object or configuration change. Every
deterministic verification/decode failure is therefore non-retryable (retrying identical bytes
fails identically -- the fail-closed default); the only registered transient is `NotDelivered`
(a carriage delivery that did not complete may complete on a later attempt).

DUAL-CARRIAGE RULES (design.md §3.5, graded by the reject/opaque cases below):
  * a naalp-error whose `code` (field 1) is registered MUST carry the registered `name` (field 2);
    a code/name disagreement is rejected `Malformed` (the strengthening direction).
  * a `code` outside the receiver's registry snapshot MUST NOT be fatal: the registry is open
    (RFC Required), so the error is treated as opaque -- the name is diagnostic only and no
    semantics are inferred -- for forward compatibility with a later-registered code.

Generated by tools/error_codes_oracle.py; do not hand-edit the emitted files.
"""
